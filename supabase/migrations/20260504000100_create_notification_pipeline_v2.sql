create or replace function public.upsert_notification_queue_item(
  input_notification_type text,
  input_dedupe_key text,
  input_payload jsonb,
  input_scheduled_for timestamptz
)
returns public.notification_queue
language plpgsql
security definer
set search_path = public
as $$
declare
  resulting_row public.notification_queue;
begin
  insert into public.notification_queue (
    notification_type,
    dedupe_key,
    payload,
    scheduled_for
  )
  values (
    input_notification_type,
    input_dedupe_key,
    input_payload,
    input_scheduled_for
  )
  on conflict (dedupe_key) do update
  set notification_type = excluded.notification_type,
      payload = excluded.payload,
      scheduled_for = excluded.scheduled_for,
      status = case
        when public.notification_queue.status = 'sent' then public.notification_queue.status
        else 'pending'
      end,
      retry_count = case
        when public.notification_queue.status = 'sent' then public.notification_queue.retry_count
        else 0
      end,
      last_error = case
        when public.notification_queue.status = 'sent' then public.notification_queue.last_error
        else null
      end,
      locked_at = case
        when public.notification_queue.status = 'sent' then public.notification_queue.locked_at
        else null
      end,
      sent_at = case
        when public.notification_queue.status = 'sent' then public.notification_queue.sent_at
        else null
      end,
      updated_at = now()
  returning * into resulting_row;

  return resulting_row;
end;
$$;

revoke all on function public.upsert_notification_queue_item(text, text, jsonb, timestamptz)
  from public;
revoke all on function public.upsert_notification_queue_item(text, text, jsonb, timestamptz)
  from anon;
revoke all on function public.upsert_notification_queue_item(text, text, jsonb, timestamptz)
  from authenticated;
grant execute on function public.upsert_notification_queue_item(text, text, jsonb, timestamptz)
  to service_role;

create or replace function public.claim_notification_queue_items(batch_size integer default 25)
returns setof public.notification_queue
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidates as (
    select queue.id
    from public.notification_queue as queue
    where queue.status = 'pending'
      and queue.scheduled_for <= now()
      and (
        queue.locked_at is null
        or queue.locked_at < now() - interval '15 minutes'
      )
    order by queue.scheduled_for asc, queue.id asc
    for update skip locked
    limit greatest(batch_size, 1)
  ),
  claimed as (
    update public.notification_queue as queue
    set status = 'processing',
        locked_at = now(),
        updated_at = now()
    where queue.id in (select id from candidates)
    returning queue.*
  )
  select *
  from claimed
  order by scheduled_for asc, id asc;
end;
$$;

revoke all on function public.claim_notification_queue_items(integer) from public;
revoke all on function public.claim_notification_queue_items(integer) from anon;
revoke all on function public.claim_notification_queue_items(integer) from authenticated;
grant execute on function public.claim_notification_queue_items(integer) to service_role;

create or replace function public.unschedule_notification_v2_jobs()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_job record;
begin
  for current_job in
    select jobid
    from cron.job
    where jobname in ('fn-planner-v2-weekly', 'fn-dispatcher-v2-minute')
  loop
    perform cron.unschedule(current_job.jobid);
  end loop;
end;
$$;

create or replace function public.schedule_notification_v2_jobs(
  project_url_secret_name text default 'project_url',
  edge_secret_name text default 'secret_token',
  planner_schedule text default '0 6 * * 1',
  dispatcher_schedule text default '* * * * *'
)
returns table (planner_job_id bigint, dispatcher_job_id bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  project_url text;
  edge_secret text;
begin
  select decrypted_secret into project_url
  from vault.decrypted_secrets
  where name = project_url_secret_name;

  select decrypted_secret into edge_secret
  from vault.decrypted_secrets
  where name = edge_secret_name;

  if project_url is null or edge_secret is null then
    raise exception 'Missing project_url or secret_token secret in Vault.';
  end if;

  perform public.unschedule_notification_v2_jobs();

  planner_job_id := cron.schedule(
    'fn-planner-v2-weekly',
    planner_schedule,
    format(
      $job$
      select net.http_post(
        url := %L,
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'Authorization', %L
        ),
        body := '{"mode":"weekly"}'::jsonb
      );
      $job$,
      project_url || '/functions/v1/fn-planner-v2',
      'Bearer ' || edge_secret
    )
  );

  dispatcher_job_id := cron.schedule(
    'fn-dispatcher-v2-minute',
    dispatcher_schedule,
    format(
      $job$
      select net.http_post(
        url := %L,
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'Authorization', %L
        ),
        body := '{}'::jsonb
      );
      $job$,
      project_url || '/functions/v1/fn-dispatcher-v2',
      'Bearer ' || edge_secret
    )
  );

  return next;
end;
$$;

revoke all on function public.schedule_notification_v2_jobs(text, text, text, text) from public;
revoke all on function public.schedule_notification_v2_jobs(text, text, text, text) from anon;
revoke all on function public.schedule_notification_v2_jobs(text, text, text, text) from authenticated;
grant execute on function public.schedule_notification_v2_jobs(text, text, text, text)
  to service_role;

