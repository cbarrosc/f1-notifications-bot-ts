create table if not exists public.f1_sessions_cache (
  id bigint generated by default as identity primary key,
  source_key text not null unique,
  session_key bigint,
  meeting_key bigint,
  session_name text not null,
  session_type text,
  meeting_name text,
  location text,
  date_start timestamptz not null,
  date_end timestamptz,
  season_year integer not null,
  source_synced_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists f1_sessions_cache_session_key_idx
  on public.f1_sessions_cache (session_key)
  where session_key is not null;

create index if not exists f1_sessions_cache_meeting_key_idx
  on public.f1_sessions_cache (meeting_key);

create index if not exists f1_sessions_cache_date_start_idx
  on public.f1_sessions_cache (date_start);

create table if not exists public.notification_queue (
  id bigint generated by default as identity primary key,
  notification_type text not null check (
    notification_type in ('weekly_digest', 'session_reminder', 'post_race_briefing')
  ),
  dedupe_key text not null unique,
  payload jsonb not null default '{}'::jsonb,
  scheduled_for timestamptz not null,
  status text not null default 'pending' check (
    status in ('pending', 'processing', 'sent', 'failed')
  ),
  retry_count integer not null default 0 check (retry_count >= 0),
  last_error text,
  locked_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists notification_queue_status_scheduled_for_idx
  on public.notification_queue (status, scheduled_for);

create index if not exists notification_queue_locked_at_idx
  on public.notification_queue (locked_at);

create table if not exists public.delivery_logs (
  id bigint generated by default as identity primary key,
  queue_id bigint not null references public.notification_queue (id) on delete cascade,
  user_id bigint not null references public.users (user_id) on delete cascade,
  attempt integer not null check (attempt >= 1),
  status text not null check (status in ('dry_run', 'sent', 'failed', 'skipped')),
  provider text not null,
  provider_message_id text,
  error_message text,
  created_at timestamptz not null default now()
);

create index if not exists delivery_logs_queue_id_idx
  on public.delivery_logs (queue_id, created_at desc);

create index if not exists delivery_logs_queue_id_user_id_status_idx
  on public.delivery_logs (queue_id, user_id, status);

alter table public.f1_sessions_cache enable row level security;
